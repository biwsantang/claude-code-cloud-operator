#!/usr/bin/env python3
"""Generate Helm resources from the reviewed Kustomize installation, without a second hand-written source."""
import pathlib
import subprocess
root = pathlib.Path(__file__).resolve().parents[1]
chart = root / 'charts/claude-code-cloud-operator'
raw = subprocess.check_output(['kustomize', 'build', str(root/'config/install')], text=True)
(root/'deploy').mkdir(exist_ok=True)
(root/'deploy/install.yaml').write_text('# Generated by hack/package.py; do not edit.\n'+raw)
crds,resources,removal=[],[],[]
for doc in raw.split('---\n'):
    if 'kind: Namespace\n' in doc:
        continue  # Helm requires an existing release namespace; raw installation owns bootstrap labels.
    if 'kind: CustomResourceDefinition\n' in doc:
        crds.append(doc)
    else:
        removal.append(doc)
        doc=doc.replace('cloud-operator-system', '{{ .Release.Namespace }}')
        doc=doc.replace('example.invalid/operator@sha256:'+'0'*64, '{{ required "managerImage must be a tested digest-pinned image" .Values.managerImage }}')
        resources.append(doc)
(chart/'crds/definitions.yaml').write_text('# Generated by hack/package.py; do not edit.\n'+'---\n'.join(crds))
(chart/'templates/installation.yaml').write_text('# Generated by hack/package.py; do not edit.\n'+'---\n'.join(resources))
(root/'deploy/uninstall.yaml').write_text('# Generated by hack/package.py; drain Fleets before applying deletion.\n'+'---\n'.join(removal))
# Optional Fleet comes from the same reviewed sample, not another raw install source.
fleet = (root/'config/samples/runners_v1alpha1_clauderunnerfleet.yaml').read_text()
fleet = fleet.replace('    app.kubernetes.io/managed-by: kustomize', '    app.kubernetes.io/managed-by: Helm')
fleet = fleet.replace('    argocd.argoproj.io/sync-options: Prune=false,Delete=false', '    argocd.argoproj.io/sync-options: Prune=false,Delete=false,SkipDryRunOnMissingResource=true\n    argocd.argoproj.io/sync-wave: "20"\n    helm.sh/resource-policy: keep')
replacements = {
    'name: example\n': 'name: {{ .Values.fleet.name | quote }}\n',
    'namespace: cloud-operator-system': 'namespace: {{ .Release.Namespace }}',
    'suspended: true': 'suspended: {{ .Values.fleet.suspended }}',
    'environmentID: ccpool_REPLACE_ME': 'environmentID: {{ .Values.fleet.environmentID | quote }}',
    'name: example-environment': 'name: {{ .Values.fleet.environmentSecretRef | quote }}',
    'name: example-network-report': 'name: {{ .Values.fleet.networkReportRef | quote }}',
    'orchestratorImage: example.invalid/runtime@sha256:'+'a'*64: 'orchestratorImage: {{ .Values.fleet.runtimeImage | quote }}',
    'hookImage: example.invalid/hook@sha256:'+'a'*64: 'hookImage: {{ .Values.fleet.hookImage | quote }}',
    'orchestratorReplicas: 2': 'orchestratorReplicas: {{ .Values.fleet.orchestratorReplicas }}',
    'runnerImage: example.invalid/runtime@sha256:'+'a'*64: 'runnerImage: {{ .Values.fleet.runtimeImage | quote }}',
    'securityRevision: replace-after-network-acceptance': 'securityRevision: {{ .Values.fleet.securityRevision | quote }}',
    'url: http://proxy.proxy.svc:3128': 'url: {{ .Values.fleet.proxy.url | quote }}',
    'namespace: proxy': 'namespace: {{ .Values.fleet.proxy.namespace | quote }}',
    'podLabels:\n        app: proxy': 'podLabels: {{ toYaml .Values.fleet.proxy.podLabels | nindent 8 }}',
    'port: 3128': 'port: {{ .Values.fleet.proxy.port }}',
    'resources:\n      requests:\n        cpu: "1"\n        memory: 2Gi\n      limits:\n        memory: 4Gi': 'resources: {{ toYaml .Values.fleet.resources | nindent 6 }}',
    'workspaceSize: 8Gi': 'workspaceSize: {{ .Values.fleet.workspaceSize | quote }}',
    'lifecycle:\n      idleMinutes: 30\n      maxSessionMinutes: 480\n      shutdownWaitSeconds: 300\n      promptToSave: true\n      pushOutcomeOnRelease: false': 'lifecycle: {{ toYaml .Values.fleet.session | nindent 6 }}\n    {{- with .Values.fleet.hostConfigRef }}\n    hostConfigRef:\n      name: {{ . | quote }}\n    {{- end }}',
}
for old, new in replacements.items():
    if old not in fleet:
        raise SystemExit('Fleet sample changed; update its explicit chart mapping: '+old.splitlines()[0])
    fleet = fleet.replace(old, new)
(chart/'templates/fleet.yaml').write_text('# Generated by hack/package.py; do not edit.\n{{- if .Values.fleet.enabled }}\n{{- if and (gt (int .Values.fleet.session.idleMinutes) 0) (gt (int .Values.fleet.session.maxSessionMinutes) 0) (gt (int .Values.fleet.session.idleMinutes) (int .Values.fleet.session.maxSessionMinutes)) }}\n{{- fail "positive fleet.session.idleMinutes cannot exceed maxSessionMinutes" }}\n{{- end }}\n'+fleet+'{{- end }}\n')
